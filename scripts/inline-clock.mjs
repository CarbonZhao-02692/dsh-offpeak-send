// 把 lib/core/{holidays,clock}.js 内联进 lib/client.js（client bundle 不能 import 宿主文件）。
// 只在标记区间内替换，client 其余代码手写不动。
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CLIENT = join(ROOT, 'lib/client.js')
const BEGIN = '// <clock:begin> — generated by scripts/inline-clock.mjs, do not edit by hand'
const END = '// <clock:end>'

const strip = (src) => src
  .replace(/^\s*import[\s\S]*?from\s+'[^']+'\s*;?\s*$/gm, '')
  .replace(/\bexport\s+(const|function|let|class)\b/g, '$1')
  .trim()

const body = [strip(readFileSync(join(ROOT, 'lib/core/holidays.js'), 'utf8')),
              strip(readFileSync(join(ROOT, 'lib/core/clock.js'), 'utf8'))].join('\n\n')

const src = readFileSync(CLIENT, 'utf8')
const b = src.indexOf(BEGIN)
const e = src.indexOf(END)
if (b < 0 || e < 0) { console.error('inline-clock: lib/client.js 缺少 <clock:begin>/<clock:end> 标记'); process.exit(1) }
const out = src.slice(0, b + BEGIN.length) + '\n' + body + '\n' + src.slice(e)
writeFileSync(CLIENT, out)
console.log('inline-clock: ok', body.length, 'chars')
