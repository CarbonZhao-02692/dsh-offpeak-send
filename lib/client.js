		//#region apply
		function apply(ctx) {
			initChannel();
			tickLoop();
			void refreshConfig(true);

			ctx.effect(
				() => {
					tickLoop();
					return () => {
						stopTicker();
						stopPolling();
						try {
							if (channel) channel.close();
						} catch (err) {
							/* 忽略 */
						}
						channel = null;
					};
				},
				'offpeak: runtime',
			);

			ctx.effect(
				() =>
					ctx.slots.inject('conversation.input.left', () =>
						ctx.slots.register(
							{
								name: 'conversation.input.left',
								id: 'offpeak-chip',
								order: 50,
								inject: (sessionId) => ({ offpeakSessionId: sessionId }),
							},
							OffpeakChip,
						),
					),
				'offpeak: chip',
			);

			ctx.effect(
				() =>
					ctx.slots.inject('conversation.input.dock', () =>
						ctx.slots.register(
							{
								name: 'conversation.input.dock',
								id: 'offpeak-dock',
								order: 20,
								inject: (sessionId) => ({ offpeakSessionId: sessionId }),
							},
							OffpeakDock,
						),
					),
				'offpeak: dock',
			);

			// 注入器骨架校验要求 client bundle 至少注册一个白名单 slot 作为挂载锚点
			// （生态惯例：sidebar-hider 也注册 shell.overlay 并返回 null）。这里不渲染任何内容。
			ctx.effect(
				() =>
					ctx.slots.inject('shell.overlay', () =>
						ctx.slots.register({ name: 'shell.overlay', id: 'offpeak-anchor', order: 900 }, () => null),
					),
				'offpeak: anchor',
			);

			let injected = false;
			if (typeof ctx.inject === 'function') {
				try {
					ctx.inject(['conversation'], (scope) => {
						installWrapper(scope);
					});
					injected = true;
				} catch (err) {
					console.warn('[offpeak] ctx.inject 不可用，退回立即安装：', err && err.message);
				}
			}
			if (!injected) {
				if (ctx.get('conversation')) installWrapper(ctx);
				else console.warn('[offpeak] conversation 服务不可用，排队功能未启用');
			}
		}
