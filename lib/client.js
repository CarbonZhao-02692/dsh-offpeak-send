		function renderDockRow(item, ctx) {
			const now = ctx.now;
			const actions = ctx.actions;
			const attachments = attachmentSummary(item.attachments);
			const isFailed = item.status === 'failed';
			const isSending = item.status === 'sending';
			const sendAt = typeof item.sendAt === 'number' ? item.sendAt : 0;
			const remaining = sendAt > 0 ? sendAt - now : 0;

			const cells = [];
			cells.push(h('span', { key: 'summary', style: { color: 'var(--dsw-alias-label-primary)', minWidth: 0, overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap', flex: '1 1 160px' } }, summarizeText(item.text)));
			if (attachments) cells.push(h('span', { key: 'atts', style: { color: 'var(--dsw-alias-label-tertiary)', whiteSpace: 'nowrap' } }, '📎 ' + attachments));

			if (isSending) {
				cells.push(h('span', { key: 'state', style: { color: 'var(--dsw-alias-label-tertiary)', whiteSpace: 'nowrap' } }, '正在发送…'));
			} else if (isFailed) {
				const errorText = (item.lastError && (item.lastError.message || item.lastError.code)) || item.lastError || '投递失败';
				const errorCode = (item.lastError && item.lastError.code) || '';
				cells.push(
					h(
						'span',
						{ key: 'state', style: { color: 'var(--dsw-alias-state-error-primary)', whiteSpace: 'nowrap' } },
						(errorCode ? errorCode + ' ' : '') + String(errorText),
					),
				);
			} else if (sendAt > 0) {
				cells.push(h('span', { key: 'state', style: { whiteSpace: 'nowrap' } }, fmtClockSec(sendAt) + ' 后发送'));
				cells.push(h('span', { key: 'left', style: { color: 'var(--dsw-alias-label-tertiary)', whiteSpace: 'nowrap' } }, '剩余 ' + fmtRemaining(remaining)));
			}

			const buttons = [];
			if (isFailed) {
				buttons.push(h('button', { key: 'retry', type: 'button', style: S.smallButton, onClick: () => { void retryItem(item.id); } }, '重试'));
				buttons.push(h('button', { key: 'cancel', type: 'button', style: S.smallButton, onClick: () => { void cancelItem(item.id); } }, '取消'));
			} else if (isSending) {
				buttons.push(h('span', { key: 'busy', style: { color: 'var(--dsw-alias-label-tertiary)' } }, '…'));
			} else {
				buttons.push(h('button', { key: 'now', type: 'button', style: S.smallButton, onClick: () => { void sendNow(item.id); } }, '立即发送'));
				buttons.push(h('button', { key: 'edit', type: 'button', style: S.smallButton, onClick: () => { requestEdit(item, actions); } }, '修改'));
				buttons.push(h('button', { key: 'cancel', type: 'button', style: S.smallButton, onClick: () => { void cancelItem(item.id); } }, '取消'));
			}

			const model = item.submittedModel;
			const rowStyle = Object.assign({}, S.row, isFailed ? { background: 'var(--dsw-alias-interactive-bg-hover-danger, rgba(229,72,77,0.08))', borderRadius: 6, padding: '4px 6px' } : null);

			const children = [h('div', { key: 'left', style: Object.assign({}, S.row, { flex: '1 1 auto', gap: 6, minWidth: 0 }) }, cells)];
			if (model) children.push(h('span', { key: 'model', style: { fontSize: 11, color: 'var(--dsw-alias-label-tertiary)', whiteSpace: 'nowrap' } }, '提交时模型 ' + String(model)));
			children.push(h('span', { key: 'actions', style: { display: 'inline-flex', gap: 6 } }, buttons));

			return h('div', { key: item.id, style: rowStyle, 'data-offpeak-item': item.id, 'data-offpeak-status': item.status }, children);
		}
