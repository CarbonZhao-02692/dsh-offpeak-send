		async function stageComposerAttachment(attachment) {
			const file = attachment && attachment.file;
			if (!file || typeof file.arrayBuffer !== 'function') throw new Error('附件不可读');
			const kind = attachment.kind === 'image' ? 'image' : 'file';
			const name = (attachment && attachment.name) || file.name || (kind === 'image' ? 'image' : 'file');
			const bytes = await file.arrayBuffer();
			const headers = {
				accept: 'application/json',
				'x-offpeak-kind': kind,
				'x-offpeak-name': encodeURIComponent(name),
			};
			if (kind === 'image') headers['x-offpeak-media-type'] = file.type || attachment.mediaType || 'image/png';
			const res = await fetch(API + '/stage', { method: 'POST', headers, body: bytes });
			const body = await readJson(res);
			if (!res.ok || !body || body.ok !== true || !body.ref) throw httpError(res.status, body, '附件暂存失败');
			return body.ref;
		}

		function notifyQueued(body) {
			if (body && body.delivered === true) {
				notify('当前已是谷时，已直接投递', 'info');
				return;
			}
			if (body && body.item && typeof body.item.sendAt === 'number') {
				notify('已排队，' + fmtClockSec(body.item.sendAt) + ' 自动发送', 'info');
				return;
			}
			notify('已进入谷时排队', 'info');
		}

		function recoverDraft(scope, text) {
			try {
				const actions = scope && typeof scope.get === 'function' ? scope.get('inputActions') : undefined;
				if (actions && typeof actions.setDraft === 'function' && text) {
					actions.setDraft(text);
					return;
				}
				console.warn('[offpeak] 无法自动回填草稿（inputActions 不可用），原文保留在错误提示中');
			} catch (err) {
				console.warn('[offpeak] 回填草稿失败：', err && err.message);
			}
		}

		function makeWrapper(original, scope) {
			const wrapped = async function offpeakSendSession(session, text, attachmentIds, mode, signal) {
				const state = store.get();
				const ids = Array.isArray(attachmentIds) ? attachmentIds : [];
				const plain = typeof text === 'string' ? text : '';
				const passthrough = () => original.call(this, session, text, attachmentIds, mode, signal);

				if (!state.enabled) return passthrough();
				if (mode === 'steer') return passthrough();
				if (plain === '' && ids.length === 0) return passthrough();
				if (phaseAt(Date.now(), effectiveConfig()) === 'offpeak') return passthrough();

				const sessionId = session && session.sessionId;
				if (typeof sessionId !== 'string' || sessionId === '') {
					console.warn('[offpeak] 会话 id 不可用，跳过排队');
					return passthrough();
				}

				let resolved = null;
				try {
					if (typeof this.resolveDraftAttachments !== 'function') throw new Error('resolveDraftAttachments 不可用');
					resolved = this.resolveDraftAttachments(ids);
					if (!Array.isArray(resolved) || resolved.length !== ids.length) throw new Error('草稿附件已变化');
					const attachments = [];
					for (const attachment of resolved) attachments.push(await stageComposerAttachment(attachment));
					const body = await apiPost('/enqueue', {
						clientTag: makeTag(),
						sessionId,
						text: plain,
						attachments,
					});
					try {
						if (typeof this.releaseDraftAttachments === 'function') this.releaseDraftAttachments(resolved);
					} catch (releaseErr) {
						console.warn('[offpeak] 释放草稿附件失败：', releaseErr && releaseErr.message);
					}
					notifyQueued(body);
					broadcastChanged();
					pollNow();
					return { kind: 'success' };
				} catch (err) {
					const code = (err && err.code) || 'ENQUEUE_FAILED';
					console.warn('[offpeak] 排队失败，回退为直接发送：', code, err && err.message);
					if ((err && err.status === 413) || code === 'PAYLOAD_TOO_LARGE' || code === 'ATTACHMENT_TOO_LARGE') {
						notify('附件超出限制，已直接发送', 'error');
					} else {
						notify('排队失败（' + code + '），已直接发送', 'error');
					}
					recoverDraft(scope, plain);
					try {
						const result = await passthrough();
						return result;
					} catch (sendErr) {
						throw sendErr;
					}
				}
			};
			wrapped[WRAPPED] = true;
			return wrapped;
		}

		function installWrapper(scope) {
			scope.effect(() => {
				const conversation = scope.get('conversation');
				if (!conversation) {
					store.set({ wrap: { active: false, reason: 'conversation 未就绪' } });
					return;
				}
				const proto = Object.getPrototypeOf(conversation);
				if (!proto || typeof proto.sendSession !== 'function') {
					console.warn('[offpeak] 未找到 conversation.sendSession，排队功能不可用');
					store.set({ wrap: { active: false, reason: '缺少 sendSession' } });
					return;
				}
				const original = proto.sendSession;
				if (original[WRAPPED]) {
					store.set({ wrap: { active: true, reason: '已由其他实例接管' } });
					return;
				}
				const wrapped = makeWrapper(original, scope);
				proto.sendSession = wrapped;
				store.set({ wrap: { active: true, reason: '已接管' } });
				console.info('[offpeak] 已接管 conversation.sendSession（高峰时段排队）');
				return () => {
					if (proto.sendSession === wrapped) {
						proto.sendSession = original;
					} else {
						console.warn('[offpeak] sendSession 已被其他插件替换，跳过还原');
					}
					store.set({ wrap: { active: false, reason: '已卸载' } });
				};
			}, 'offpeak: sendSession');
		}
