		function OffpeakChip(props) {
			const state = useStore();
			const sessionId = props.offpeakSessionId || props.sessionId || '';
			React.useEffect(() => addInterest(sessionId), [sessionId]);

			const config = configOf(state);
			const enabled = state.enabled;
			const phase = phaseOf(state);
			const items = activeItemsOf(state, sessionId);
			const count = items.length;
			const waiting = items.filter((item) => item.status === 'waiting' || item.status === 'sending');
			const earliest = waiting.reduce((acc, item) => {
				const at = typeof item.sendAt === 'number' ? item.sendAt : 0;
				return at > 0 && (acc === 0 || at < acc) ? at : acc;
			}, 0);

			let dotColor = 'var(--dsw-alias-label-tertiary)';
			let label = '谷时';
			let title = '';
			const bufferSec = Math.round(config.bufferMs / 1000) || 3;

			if (!enabled) {
				dotColor = 'var(--dsw-alias-label-tertiary)';
				label = '谷时';
				title = '谷时发送：关闭。开启后高峰时段按发送会排队到谷时开始 ' + bufferSec + ' 秒后投递。';
			} else if (phase === 'offpeak') {
				dotColor = 'var(--dsw-alias-state-success-primary)';
				label = '谷时';
				title = '谷时发送：开启。当前空闲时段（半价），发送立即投递。下次高峰 ' + fmtClock(boundaryOf(state, 'peak')) + '。';
			} else {
				const target = boundaryOf(state, 'offpeak') + config.bufferMs;
				dotColor = 'var(--dsw-alias-state-warn-primary)';
				label = '谷时 ' + fmtClock(target) + ' 后发';
				title = '谷时发送：开启。当前高峰时段，发送将排队至 ' + fmtClockSec(target) + '。';
			}
			if (count > 0 && earliest > 0) {
				title += ' 排队 ' + count + ' 条，最早 ' + fmtClockSec(earliest) + ' 投递。';
			}
			title += ' 仅对普通发送生效；追问/插话（steer）不排队。';

			const longPressedRef = React.useRef(false);
			const pressTimerRef = React.useRef(null);

			const clearPressTimer = () => {
				if (pressTimerRef.current !== null) {
					clearTimeout(pressTimerRef.current);
					pressTimerRef.current = null;
				}
			};

			const onToggle = () => {
				if (longPressedRef.current) {
					longPressedRef.current = false;
					return;
				}
				if (state.enabled) {
					if (waiting.length > 0) {
						store.set({
							dialog: {
								kind: 'close',
								sessionId,
								count: waiting.length,
								earliest,
								others: (state.pendingBySession[sessionId] && state.pendingBySession[sessionId].others) || 0,
							},
						});
						return;
					}
					setEnabled(false);
					return;
				}
				setEnabled(true);
			};

			const chipNode = h(
				'button',
				{
					type: 'button',
					style: Object.assign({}, S.buttonReset, S.chip),
					title,
					'aria-pressed': enabled ? 'true' : 'false',
					'aria-label': '谷时发送' + (enabled ? '（已开启）' : '（已关闭）'),
					'data-offpeak-chip': enabled ? 'on' : 'off',
					onClick: onToggle,
					onContextMenu: (event) => {
						event.preventDefault();
						openSettings(sessionId);
					},
					onPointerDown: (event) => {
						if (event && typeof event.button === 'number' && event.button !== 0) return;
						clearPressTimer();
						longPressedRef.current = false;
						pressTimerRef.current = setTimeout(() => {
							pressTimerRef.current = null;
							longPressedRef.current = true;
							openSettings(sessionId);
						}, 600);
					},
					onPointerUp: clearPressTimer,
					onPointerLeave: clearPressTimer,
					onPointerCancel: clearPressTimer,
				},
				h('span', { style: Object.assign({}, S.dot, { background: dotColor }) }),
				h('span', null, label),
				count > 0 ? h('span', { style: S.badge }, count > BADGE_MAX ? BADGE_MAX + '+' : String(count)) : null,
			);

			return h(
				React.Fragment,
				null,
				chipNode,
				state.dialog ? h(DialogOverlay, { dialog: state.dialog }) : null,
				state.panel ? h(SettingsPanel, { panel: state.panel }) : null,
				state.toast ? h(ToastView, { toast: state.toast }) : null,
			);
		}
